export function getCommandIcon(id: string): IconName {
  if (id.startsWith('heading-')) return 'heading';
  if (id.startsWith('custom:') || id.startsWith('freeform-')) return 'sparkles';
  if (id.startsWith('slash-')) return commandIcons[id.slice(6)] || 'chatAi';
  return commandIcons[id] || 'sparkles';
}
